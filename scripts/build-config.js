// Generates js/config.js from environment variables at build time (Vercel) or locally.
// No dependencies. If no variables are set, the existing js/config.js is left untouched.
//
// Variables (first one found wins):
//   SUPABASE_URL            | NEXT_PUBLIC_SUPABASE_URL
//   SUPABASE_PUBLISHABLE_KEY | NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY | SUPABASE_ANON_KEY
//   WHATSAPP_NUMBER         (international format, digits only, e.g. 919876543210)
//
// Only PUBLIC values belong here. Never put a service_role / sb_secret_ key in this site.

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');

// Local convenience: read .env if present (Vercel injects real env vars itself).
try {
  const envFile = fs.readFileSync(path.join(root, '.env'), 'utf8');
  envFile.split(/\r?\n/).forEach(line => {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  });
} catch (e) { /* no .env file: fine */ }

const pick = (...names) => names.map(n => process.env[n]).find(v => v && v.trim());

const url = pick('SUPABASE_URL', 'NEXT_PUBLIC_SUPABASE_URL');
const key = pick('SUPABASE_PUBLISHABLE_KEY', 'NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY', 'SUPABASE_ANON_KEY');
const wa = pick('WHATSAPP_NUMBER');

if (!url && !key && !wa) {
  console.log('[build-config] no env variables set, keeping existing js/config.js');
  process.exit(0);
}

// Start from the current file so unset variables keep their existing value.
const cfgPath = path.join(root, 'js', 'config.js');
const current = fs.readFileSync(cfgPath, 'utf8');
const read = name => (current.match(new RegExp(name + ":\\s*'([^']*)'")) || [])[1] || '';

const final = {
  whatsapp: (wa || read('whatsapp')).replace(/\D/g, ''),
  url: (url || read('url')).replace(/\/+$/, ''),
  anonKey: key || read('anonKey')
};

if (/^sb_secret_|service_role/.test(final.anonKey)) {
  console.error('[build-config] refusing to build: that looks like a SECRET key. Use the publishable key.');
  process.exit(1);
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(final.url)) {
  console.error('[build-config] SUPABASE_URL looks wrong: ' + final.url);
  process.exit(1);
}
if (!final.anonKey) {
  console.error('[build-config] missing Supabase publishable key');
  process.exit(1);
}

const out = `// Generated by scripts/build-config.js from environment variables. Public values only.
window.BPS_CONFIG = {
  // WhatsApp number for orders, international format, digits only.
  whatsapp: '${final.whatsapp}',
  url: '${final.url}',
  anonKey: '${final.anonKey}'
};
`;
fs.writeFileSync(cfgPath, out);
console.log('[build-config] wrote js/config.js for ' + final.url);
